import React from 'react'
import { ScrollView, StyleSheet, Text, View } from 'react-native'
import { SafeAreaView } from 'react-native-safe-area-context'
import { useRoute, type RouteProp } from '@react-navigation/native'
import type { HomeStackParamList } from '../../../navigation/types'

type ScreenRoute = RouteProp<HomeStackParamList, 'MacroInfo'>

const colors = {
    background: '#F4F7FB',
    card: '#FFFFFF',
    primary: '#1D3557',
    secondary: '#4A627A',
    accent: '#F4A261',
    border: '#E6ECF4',
}

const MacroInfoScreen = () => {
    const route = useRoute<ScreenRoute>()
    const {
        protein,
        proteinTarget,
        carbs,
        carbsTarget,
        fats,
        fatsTarget,
        calories,
        caloriesTarget,
    } = route.params

    const p = proteinTarget > 0 ? Math.min(Math.round((protein / proteinTarget) * 100), 100) : 0
    const c = carbsTarget > 0 ? Math.min(Math.round((carbs / carbsTarget) * 100), 100) : 0
    const f = fatsTarget > 0 ? Math.min(Math.round((fats / fatsTarget) * 100), 100) : 0
    const cal = caloriesTarget > 0 ? Math.min(Math.round((calories / caloriesTarget) * 100), 100) : 0

    return (
        <SafeAreaView style={styles.screen}>
            <ScrollView contentContainerStyle={styles.content} showsVerticalScrollIndicator={false}>
                <View style={styles.heroCard}>
                    <Text style={styles.eyebrow}>Transparency</Text>
                    <Text style={styles.title}>Macro Progress</Text>
                    <Text style={styles.subtitle}>This is how each macro bar and percentage is computed.</Text>
                </View>

                <View style={styles.card}>
                    <Text style={styles.sectionTitle}>Formula</Text>
                    <Text style={styles.formula}>Macro Progress % = (Consumed Macro / Macro Target) x 100</Text>
                    <Text style={styles.formula}>Calorie Progress % = (Consumed Calories / Calorie Target) x 100</Text>
                </View>

                <View style={styles.card}>
                    <Text style={styles.sectionTitle}>Your Numbers Today</Text>
                    <View style={styles.row}><Text style={styles.label}>Calories</Text><Text style={styles.value}>{calories}/{caloriesTarget} ({cal}%)</Text></View>
                    <View style={styles.row}><Text style={styles.label}>Protein</Text><Text style={styles.value}>{protein}g/{proteinTarget}g ({p}%)</Text></View>
                    <View style={styles.row}><Text style={styles.label}>Carbs</Text><Text style={styles.value}>{carbs}g/{carbsTarget}g ({c}%)</Text></View>
                    <View style={styles.row}><Text style={styles.label}>Fats</Text><Text style={styles.value}>{fats}g/{fatsTarget}g ({f}%)</Text></View>
                </View>

                <View style={styles.card}>
                    <Text style={styles.sectionTitle}>How Targets Are Set</Text>
                    <Text style={styles.note}>Targets come from your Personalization settings. If you use auto formulas, targets are generated by your selected mode. If you use custom mode, targets come from your exact manual values.</Text>
                </View>
            </ScrollView>
        </SafeAreaView>
    )
}

const styles = StyleSheet.create({
    screen: { flex: 1, backgroundColor: colors.background },
    content: { padding: 18, paddingBottom: 36, gap: 14 },
    heroCard: {
        backgroundColor: colors.card,
        borderRadius: 16,
        padding: 16,
        borderWidth: 1,
        borderColor: colors.border,
        gap: 4,
    },
    eyebrow: { color: colors.accent, fontSize: 12, fontWeight: '700', letterSpacing: 0.7, textTransform: 'uppercase' },
    title: { color: colors.primary, fontSize: 24, fontWeight: '700' },
    subtitle: { color: colors.secondary, fontSize: 14, lineHeight: 20 },
    card: {
        backgroundColor: colors.card,
        borderRadius: 16,
        padding: 16,
        borderWidth: 1,
        borderColor: colors.border,
        gap: 10,
    },
    sectionTitle: { color: colors.primary, fontSize: 16, fontWeight: '700' },
    formula: { color: colors.secondary, fontSize: 14, lineHeight: 22, fontWeight: '600' },
    row: { flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center' },
    label: { color: colors.secondary, fontSize: 14 },
    value: { color: colors.primary, fontSize: 14, fontWeight: '700' },
    note: { color: colors.secondary, fontSize: 14, lineHeight: 22 },
})

export default MacroInfoScreen
